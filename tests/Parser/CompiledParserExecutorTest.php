<?php

declare(strict_types=1);

namespace FFI\Parser\Tests\Parser;

use FFI\Parser\Parser\CompiledParserExecutor;
use FFI\Parser\Tests\TestCase;
use Phplrt\Compiler\Compiler;
use Phplrt\Compiler\Generator\ClassModifier;
use Phplrt\Compiler\Generator\TargetPhpVersion;
use Phplrt\Source\FileSource;
use PHPUnit\Framework\Attributes\CoversNothing;

#[CoversNothing]
final class CompiledParserExecutorTest extends TestCase
{
    private const GRAMMAR = __DIR__ . '/../../resources/grammar.pp3';

    private const COMPILED = __DIR__ . '/../../src/Parser/CompiledParserExecutor.php';

    /**
     * Mirrors the settings of bin/build-parser.
     */
    public function testParserIsNotStale(): void
    {
        $actual = \file_get_contents(self::COMPILED);

        self::assertIsString($actual);

        // The output depends on the compiler, and the dependencies installed
        // with --prefer-lowest may be older than the ones the parser has
        // been generated by.
        if (\preg_match('/compiler v(\S+)/', $actual, $matches) !== 1) {
            self::fail('The version of the compiler is not found in the generated parser');
        }

        if ($matches[1] !== Compiler::getVersion()) {
            self::markTestSkipped(\sprintf(
                'The parser has been generated by phplrt/compiler %s, but %s is installed',
                $matches[1],
                Compiler::getVersion(),
            ));
        }

        $expected = (string) (new Compiler())
            ->load(FileSource::createFromPathname(self::GRAMMAR))
            ->generate()
            ->withNamespaceName('FFI\Parser\Parser')
            ->withClassName('CompiledParserExecutor')
            ->withClassModifier(ClassModifier::Abstract)
            ->withTargetPhpVersion(TargetPhpVersion::Php81);

        self::assertSame($expected, $actual, \sprintf(
            '%s is stale, run "composer grammar:build"',
            CompiledParserExecutor::class,
        ));
    }
}
